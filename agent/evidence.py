"""Evidence Ledger and Provenance Tracking for RALLY Agent.

Stores, validates, and correlates evidence items derived exclusively from
approved tool calls or deterministic logical inference.
Ensures every hypothesis or conclusion maps explicitly to evidence IDs.
"""

from typing import Any
from agent.models import EvidenceItem, EvidenceLabel, ConfidenceLevel
from agent.policies import AgentPolicyEngine


class EvidenceLedger:
    """Immutable ledger of recorded evidence with provenance tracking."""

    def __init__(self, max_items: int = 50):
        self._items: list[EvidenceItem] = []
        self._max_items = max_items
        self._counter = 0

    def add_evidence(
        self,
        source_tool: str,
        source_reference: str,
        observation: str,
        data: dict[str, Any],
        label: EvidenceLabel = EvidenceLabel.OBSERVED,
        confidence: ConfidenceLevel = ConfidenceLevel.HIGH,
        timestamp: str = "",
    ) -> EvidenceItem:
        """Records a new evidence item with strict provenance and label validation."""
        if len(self._items) >= self._max_items:
            raise RuntimeError(f"Evidence ledger reached maximum capacity of {self._max_items} items")

        # Enforce that EXECUTED or VERIFIED cannot be emitted during investigation
        AgentPolicyEngine.validate_evidence_label(label, action_executed=False)

        # Sanitize observations to prevent untrusted prompt injection
        clean_obs = AgentPolicyEngine.sanitize_untrusted_content(observation)

        self._counter += 1
        ev_id = f"EV-{self._counter:03d}"

        item = EvidenceItem(
            evidence_id=ev_id,
            source_tool=source_tool,
            source_reference=source_reference,
            observation=clean_obs,
            data=data,
            label=label,
            confidence=confidence,
            timestamp=timestamp,
        )
        self._items.append(item)
        return item

    def get_all(self) -> list[EvidenceItem]:
        """Returns all evidence items currently in the ledger."""
        return list(self._items)

    def get_by_id(self, evidence_id: str) -> EvidenceItem | None:
        """Retrieves an evidence item by ID."""
        for item in self._items:
            if item.evidence_id == evidence_id:
                return item
        return None

    def get_by_tool(self, tool_name: str) -> list[EvidenceItem]:
        """Returns all evidence items generated by a specific tool."""
        return [i for i in self._items if i.source_tool == tool_name]

    def count(self) -> int:
        """Returns total number of recorded evidence items."""
        return len(self._items)
