"""Domain models for RALLY Execution + Verification subsystem (Phase 6).

Defines schemas for:
- ExecutionStatus and ExecutionRecord
- VerificationStatus and VerificationReport
- RecoveryDecision (RESOLVED, RECOVERY_FAILED, NEEDS_HUMAN, EXECUTION_BLOCKED)
- ControlledExecutionResult
"""

from enum import Enum
from typing import Any
from pydantic import BaseModel, ConfigDict, Field

from simulator.domain.models import ServiceStatus


class ExecutionStatus(str, Enum):
    """Execution status of an action plan."""
    NOT_EXECUTED = "NOT_EXECUTED"
    EXECUTING = "EXECUTING"
    EXECUTED = "EXECUTED"
    FAILED = "FAILED"
    BLOCKED = "BLOCKED"


class VerificationStatus(str, Enum):
    """Outcome of independent verification."""
    PENDING = "PENDING"
    VERIFYING = "VERIFYING"
    PASSED = "PASSED"
    FAILED = "FAILED"
    INCONCLUSIVE = "INCONCLUSIVE"


class RecoveryDecision(str, Enum):
    """Final operational decision following execution and independent verification."""
    RESOLVED = "RESOLVED"
    RECOVERY_FAILED = "RECOVERY_FAILED"
    NEEDS_HUMAN = "NEEDS_HUMAN"
    EXECUTION_BLOCKED = "EXECUTION_BLOCKED"


class ExecutionRecord(BaseModel):
    """Immutable audit record of a controlled action execution."""
    model_config = ConfigDict(frozen=True)

    execution_id: str
    plan_id: str
    action_type: str
    target_resource: str
    target_identifier: str
    idempotency_key: str
    executed_at: str
    executed_by: str
    tool_name: str
    tool_arguments: dict[str, Any] = Field(default_factory=dict)
    tool_result: dict[str, Any] = Field(default_factory=dict)
    status: ExecutionStatus
    duration_ms: float
    error_message: str | None = None


class VerificationCheck(BaseModel):
    """Single independent check evaluated during verification."""
    model_config = ConfigDict(frozen=True)

    check_name: str
    description: str
    expected: Any
    actual: Any
    passed: bool
    evidence_reference: str


class VerificationReport(BaseModel):
    """Report generated by the independent verification engine."""
    model_config = ConfigDict(frozen=True)

    verification_id: str
    plan_id: str
    execution_id: str
    verified_at: str
    status: VerificationStatus
    checks: list[VerificationCheck] = Field(default_factory=list)
    measured_error_rate_pct: float
    service_status: ServiceStatus
    active_deployment_id: str
    dependencies_healthy: bool
    summary: str


class ControlledExecutionResult(BaseModel):
    """Composite result returned by the orchestrator for execution + verification."""
    model_config = ConfigDict(frozen=True)

    plan_id: str
    incident_id: str
    execution_record: ExecutionRecord
    verification_report: VerificationReport | None = None
    recovery_decision: RecoveryDecision
    incident_status: str
    explanation: str
